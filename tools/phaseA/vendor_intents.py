#!/usr/bin/env python3
"""Phase A step 5: write docs/vendor-intents.md for all com.tw.* / com.dofun.* packages.

Sources, best first:
  1. decompiled AndroidManifest.xml from jadx (exported flag + intent-filter actions) - authoritative
  2. mmi-carlink.txt (the MMI launcher's on-device scan): component names + string constants that
     look like broadcast actions. Actions from this source are UNCONFIRMED: they are strings found in
     the app, not proof that it sends or listens for them.
    python3 -I tools/phaseA/vendor_intents.py --carlink mmi-carlink.txt --out docs/vendor-intents.md \
        [--jadx device_dump/jadx]
"""
import argparse
import re
import xml.etree.ElementTree as ET
from collections import OrderedDict
from pathlib import Path

PKG_RX = re.compile(r"^(com\.tw\.|com\.dofun\.)")
A = "{http://schemas.android.com/apk/res/android}"
ACTION_RX = re.compile(r"^(action\.|android\.intent\.action\.|[a-z]+(\.[a-z0-9_]+)+\.(action|intent)\.|com\.(tw|dofun)\.)"
                       r"[\w.]+$", re.I)
NOISE_RX = re.compile(r"^(android\.media\.|android\.graphics\.|com\.bumptech\.|persist\.|ro\.|sys\.)")


def parse_carlink(path: Path):
    pkgs = OrderedDict()
    cur = None
    for line in path.read_text(errors="replace").splitlines():
        m = re.match(r"^== (\S+)\s+\((.*)\) ==$", line)
        if m:
            cur = m.group(1) if PKG_RX.match(m.group(1)) else None
            if cur:
                pkgs[cur] = {"label": m.group(2), "components": [], "strings": []}
            continue
        if not cur or not line.startswith("  "):
            continue
        s = line.strip()
        m = re.match(r"^(activity|service|receiver|provider)\s+(\S+)(\s+\(exported\))?$", s)
        if m:
            pkgs[cur]["components"].append((m.group(1), m.group(2), bool(m.group(3))))
        elif ACTION_RX.match(s) and not NOISE_RX.match(s) and not s.startswith(cur + "."):
            pkgs[cur]["strings"].append(s)
        elif s.startswith(("persist.", "sys.", "ro.")) and "tw" in s:
            pkgs[cur]["strings"].append(s)
    return pkgs


def parse_manifest(path: Path):
    root = ET.parse(path).getroot()
    pkg = root.get("package")
    comps = []
    for app in root.iter("application"):
        for el in app:
            if el.tag not in ("activity", "activity-alias", "service", "receiver", "provider"):
                continue
            filters = el.findall("intent-filter")
            exported = el.get(A + "exported")
            exported = (exported == "true") if exported is not None else bool(filters)
            actions = [x.get(A + "name") for f in filters for x in f.findall("action")]
            cats = [x.get(A + "name") for f in filters for x in f.findall("category")]
            comps.append({"kind": el.tag, "name": el.get(A + "name"), "exported": exported,
                          "permission": el.get(A + "permission"), "actions": actions, "categories": cats})
    return pkg, comps


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--carlink", type=Path)
    ap.add_argument("--jadx", type=Path)
    ap.add_argument("--out", type=Path, required=True)
    a = ap.parse_args()

    manifests = {}
    if a.jadx and a.jadx.is_dir():
        for mf in sorted(a.jadx.glob("*/resources/AndroidManifest.xml")):
            try:
                pkg, comps = parse_manifest(mf)
            except ET.ParseError as e:
                print(f"[vendor_intents] skip {mf}: {e}")
                continue
            if pkg and PKG_RX.match(pkg):
                manifests[pkg] = (mf, comps)
    scan = parse_carlink(a.carlink) if a.carlink and a.carlink.exists() else {}

    out = ["# Vendor components and intents", "",
           "Generated by `tools/phaseA/vendor_intents.py`.", "",
           "- **manifest**: from the decompiled `AndroidManifest.xml`. Exported flag and actions are authoritative.",
           "- **scan**: from `mmi-carlink.txt` (on-device scan by the MMI launcher). Components are real; "
           "strings are constants found in the app and are **UNCONFIRMED** as sent/received actions.", "",
           "Launch test for any activity (read-only, just opens the screen): "
           "`adb shell am start -n <pkg>/<activity>`", ""]
    for pkg in sorted(set(manifests) | set(scan)):
        label = scan.get(pkg, {}).get("label", "")
        out += [f"## {pkg}" + (f" — {label}" if label else ""), ""]
        if pkg in manifests:
            mf, comps = manifests[pkg]
            out += [f"Source: manifest `{mf}`", "", "| kind | component | exported | actions | permission |",
                    "|---|---|---|---|---|"]
            for c in comps:
                out.append(f"| {c['kind']} | `{c['name']}` | {'yes' if c['exported'] else 'no'} | "
                           f"{', '.join('`%s`' % x for x in c['actions']) or '—'} | {c['permission'] or '—'} |")
            out.append("")
        elif pkg in scan:
            s = scan[pkg]
            if s["components"]:
                out += ["Source: scan (exported = only when the scan said so; others UNKNOWN)", "",
                        "| kind | component | exported |", "|---|---|---|"]
                out += [f"| {k} | `{n}` | {'yes' if e else 'UNKNOWN'} |" for k, n, e in s["components"]]
                out.append("")
        if scan.get(pkg, {}).get("strings"):
            out += ["Action-like strings (scan, UNCONFIRMED):", "",
                    ", ".join(f"`{x}`" for x in sorted(set(scan[pkg]["strings"]))), ""]
    if pkg_note := ("com.tw.core" in scan or "com.tw.core" in manifests):
        out += ["> `com.tw.core` is listed for completeness only. It matches the package name used by "
                "reported head-unit malware; nothing from it is used by the launcher.", ""]
    a.out.write_text("\n".join(out) + "\n")
    print(f"[vendor_intents] {len(manifests)} manifest(s), {len(scan)} scanned pkg(s) -> {a.out}")


if __name__ == "__main__":
    main()
