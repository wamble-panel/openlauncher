#!/usr/bin/env python3
"""Phase A step 4: build docs/mcu-message-map.md from decompiled vendor apps.

For each subsystem package, lists every TWUtil construction, open() ID set, write() call and
handler `case N:` with file:line evidence. Everything here is static analysis: an ID is only
CONFIRMED once it has been seen in the MCU logcat on the unit (see NOTES.md for the test).
    python3 -I tools/phaseA/mcu_map.py --jadx device_dump/jadx --out docs/mcu-message-map.md
"""
import argparse
import re
from collections import defaultdict
from pathlib import Path

SUBSYSTEMS = {
    "radio": ["com.tw.radio"],
    "bluetooth": ["com.tw.bt"],
    "steering keys": ["com.tw.keypad"],
    "climate": ["com.tw.ac"],
    "car info / CAN": ["com.tw.carinfoservice", "com.tw.car"],
    "reverse camera": ["com.tw.reverse", "com.tw.service"],
    "service / ACC": ["com.tw.service", "com.tw.service.xt"],
    "eq": ["com.tw.eq"],
    "music": ["com.tw.music"],
}
# com.tw.core is deliberately excluded (reported malware vector); see NOTES.md.

NUM = r"(0x[0-9a-fA-F]+|\d+)"
PATTERNS = {
    "new": re.compile(r"new\s+TWUtil\s*\(([^)]*)\)"),
    "open": re.compile(r"\.open\s*\(\s*new\s+short\[\]\s*\{([^}]*)\}"),
    "write": re.compile(r"\.write\s*\(\s*" + NUM + r"\s*(?:,([^;]*))?\)"),
    "handler": re.compile(r"\.addHandler\s*\(([^)]*)\)"),
    "case": re.compile(r"^\s*case\s+" + NUM + r"\s*:"),
}
TW_HINT = re.compile(r"TWUtil|TWClient|handleMessage")


def to_int(s):
    s = s.strip()
    try:
        return int(s, 16) if s.lower().startswith("0x") else int(s)
    except ValueError:
        return None


def scan_pkg(root: Path):
    hits = []
    ids_open, ids_write, ids_case = set(), set(), set()
    for f in sorted(root.rglob("*.java")):
        text = f.read_text(errors="replace")
        if not TW_HINT.search(text):
            continue
        rel = f.relative_to(root.parent)
        in_handler = "handleMessage" in text
        for n, line in enumerate(text.splitlines(), 1):
            for kind, rx in PATTERNS.items():
                m = rx.search(line)
                if not m:
                    continue
                if kind == "case" and not in_handler:
                    continue
                hits.append((kind, f"{rel}:{n}", line.strip()[:160]))
                if kind == "open":
                    ids_open.update(i for i in map(to_int, m.group(1).split(",")) if i is not None)
                elif kind == "write":
                    v = to_int(m.group(1))
                    if v is not None:
                        ids_write.add(v)
                elif kind == "case":
                    v = to_int(m.group(1))
                    if v is not None and v > 255:   # small cases are usually sub-commands, not MCU IDs
                        ids_case.add(v)
    return hits, ids_open, ids_write, ids_case


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--jadx", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    a = ap.parse_args()

    out = ["# MCU message map", "",
           "Generated by `tools/phaseA/mcu_map.py` from static analysis of the decompiled vendor apps. "
           "**Every ID below is UNCONFIRMED** until it is seen in `adb logcat -s MCU` on the unit "
           "with the matching action (press the button / open the door / change the fan).", "",
           "IDs known from public projects (Radio-MST768, CarRadio), also UNCONFIRMED on this unit:", "",
           "| id | meaning | source |", "|---:|---|---|",
           "| 265 | radio region | dipcore/Radio-MST768 |",
           "| 513 | (opened by radio apps, purpose unknown) | dipcore/Radio-MST768 |",
           "| 769 | source / audio channel | dipcore/Radio-MST768 |",
           "| 1025 | tuner cmd: sub 0 autoscan, 1 seek, 4 LOC/DX, 5 band | dipcore/Radio-MST768 |",
           "| 1026 | set freq (255, freq) | dipcore/Radio-MST768 |",
           "| 1028 | RDS flags | dipcore/Radio-MST768 |",
           "| 1029 | (opened by radio apps, purpose unknown) | dipcore/Radio-MST768 |",
           "| 1030 | band params | dipcore/Radio-MST768 |",
           "| 40465 | audio focus (192,1 acquire / 192,129 release) | nikhil914/CarRadio |", ""]

    found_any = False
    for name, pkgs in SUBSYSTEMS.items():
        for pkg in pkgs:
            root = a.jadx / pkg / "sources"
            if not root.is_dir():
                continue
            found_any = True
            hits, o, w, c = scan_pkg(root)
            out += [f"## {name} — `{pkg}`", "",
                    f"- open(): {sorted(o) or '—'}",
                    f"- write() first arg: {sorted(w) or '—'}",
                    f"- handler cases > 255: {sorted(c) or '—'}", ""]
            if hits:
                out += ["<details><summary>evidence</summary>", "", "| kind | location | code |", "|---|---|---|"]
                for kind, loc, code in hits:
                    out.append(f"| {kind} | `{loc}` | `{code.replace('|', chr(92) + '|')}` |")
                out += ["", "</details>", ""]
    if not found_any:
        out += ["**Vendor apps not decompiled yet.** Run `tools/phaseA/pull_vendor.sh` then "
                "`tools/phaseA/decompile.sh`.", ""]
    a.out.write_text("\n".join(out) + "\n")
    print(f"[mcu_map] -> {a.out}")


if __name__ == "__main__":
    main()
