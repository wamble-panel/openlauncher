#!/usr/bin/env python3
"""Phase A step 3: write docs/TWUtil-API.md from the decompiled android/tw/john/ classes.

Reads jadx output only (static text); never imports or runs anything from it.
    python3 -I tools/phaseA/twutil_api.py --jadx device_dump/jadx --out docs/TWUtil-API.md
"""
import argparse
import re
from pathlib import Path

DECL = re.compile(
    r"^\s*(public|protected)\s+(?:(?:static|final|native|synchronized|abstract)\s+)*"
    r"(?:[\w<>\[\],.? ]+\s+)?(\w+)\s*\([^)]*\)"
)
FIELD = re.compile(r"^\s*public\s+(?:static\s+)?(?:final\s+)?[\w<>\[\]]+\s+\w+\s*(=[^;]*)?;")
CLASS = re.compile(r"^\s*public\s+.*\b(class|interface)\s+\w+")


def find_john_dirs(jadx: Path):
    return sorted({p.parent for p in jadx.glob("*/sources/android/tw/john/*.java")})


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--jadx", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    a = ap.parse_args()

    dirs = find_john_dirs(a.jadx)
    out = ["# android.tw.john API", "",
           "Generated by `tools/phaseA/twutil_api.py` from jadx output. Signatures are from the unit's "
           "own framework, so they are CONFIRMED as declarations; what each message ID does is documented "
           "in `mcu-message-map.md`.", ""]
    if not dirs:
        out += ["**Not generated yet**: no `*/sources/android/tw/john/*.java` under "
                f"`{a.jadx}`. Run `tools/phaseA/pull_vendor.sh` then `tools/phaseA/decompile.sh`.", ""]
    for d in dirs:
        out += [f"Source: `{d.relative_to(a.jadx)}`", ""]
        for f in sorted(d.glob("*.java")):
            out += [f"## {f.stem}", "", "| line | declaration |", "|---:|---|"]
            for n, line in enumerate(f.read_text(errors="replace").splitlines(), 1):
                s = line.strip()
                if CLASS.match(line) or DECL.match(line) or FIELD.match(line):
                    s = s.rstrip("{").strip().replace("|", "\\|")
                    out.append(f"| {n} | `{s}` |")
            out.append("")
    a.out.write_text("\n".join(out) + "\n")
    print(f"[twutil_api] {len(dirs)} source dir(s) -> {a.out}")


if __name__ == "__main__":
    main()
